export type OfficialBoardsTranslationKey = keyof typeof officialBoardsTranslations['zh-TW'];

export const useOfficialBoardsTranslation = () => {
    const { language } = useTranslation();
    const t = (key: OfficialBoardsTranslationKey, params?: Record<string, string | number>): string => {
        const dict = (officialBoardsTranslations[language] || officialBoardsTranslations['zh-TW']) as any;
        let text = dict[key] !== undefined ? dict[key] : key;
        if (params) {
            Object.entries(params).forEach(([k, v]) => {
                text = text.replace(`{${k}}`, String(v));
            });
        }
        return text;
    };
    return { t, language };
};
